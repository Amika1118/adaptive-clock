import os, re
from lupa.lua54 import LuaRuntime

HERE = os.path.dirname(os.path.abspath(__file__))

# keys the other languages did not have yet
EXTRA_T = {
    "Spanish": dict(weekendLeft="hasta el fin de semana", daylight="de luz diurna"),
    "French": dict(weekendLeft="jusqu'au week-end", daylight="de lumi\u00e8re du jour"),
    "German": dict(weekendLeft="bis zum Wochenende", daylight="Tageslicht"),
    "Portuguese": dict(weekendLeft="at\u00e9 ao fim de semana", daylight="de luz solar"),
    "Italian": dict(weekendLeft="al weekend", daylight="di luce"),
    "Sinhala": dict(weekendLeft="\u0dc3\u0dad\u0dd2 \u0d85\u0db1\u0dca\u0dad\u0dba\u0da7", daylight="\u0daf\u0dc0\u0dbd\u0dca \u0d9a\u0dcf\u0dbd\u0dba"),
    "Tamil": dict(weekendLeft="\u0bb5\u0bbe\u0bb0 \u0b87\u0bb1\u0bc1\u0ba4\u0bbf \u0bb5\u0bb0\u0bc8", daylight="\u0baa\u0b95\u0bb2\u0bcd \u0ba8\u0bc7\u0bb0\u0bae\u0bcd"),
    "Hindi": dict(weekendLeft="\u0938\u092a\u094d\u0924\u093e\u0939\u093e\u0902\u0924 \u0924\u0915", daylight="\u0926\u093f\u0928 \u0915\u093e \u0909\u091c\u093e\u0932\u093e"),
    "Japanese": dict(weekendLeft="\u9031\u672b\u307e\u3067", daylight="\u65e5\u7167\u6642\u9593"),
}

def _py(x):
    if hasattr(x, "items"):
        keys = list(x.keys())
        if keys and all(isinstance(k, int) for k in keys):
            return [_py(x[k]) for k in sorted(keys)]
        return {k: _py(v) for k, v in x.items()}
    return x

def load():
    lua = LuaRuntime(unpack_returned_tuples=True)
    data = _py(lua.execute(open(os.path.join(HERE, "languages.lua"), encoding="utf-8-sig").read()))
    english = data["English"]
    for name, d in data.items():
        t = dict(english["t"]); t.update(d.get("t", {})); t.update(EXTRA_T.get(name, {}))
        d["t"] = t
        d["greet"] = {**english["greet"], **d.get("greet", {})}
    return data

SLOT = {"n": "[mDaysLeft]", "year": "[mYear]"}

def _tpl(s):
    """'{n} days left' -> texts around the placeholders (spaces become ~; a meter Substitute turns them back) and the slot names in order."""
    texts, slots, pos = [], [], 0
    for m in re.finditer(r"\{(n|year)\}", s):
        texts.append(s[pos:m.start()].replace(" ", "~")); slots.append(m.group(1)); pos = m.end()
    texts.append(s[pos:].replace(" ", "~"))
    return texts, slots

def variables(d):
    out = []
    for key, arr in (("Dow", d["dow"]), ("DowS", d["dowS"]), ("DowH", d["dowH"]), ("Mon", d["mon"]), ("MonS", d["monS"])):
        out += [(f"{key}{i}", v) for i, v in enumerate(arr, 1)]
    g = d["greet"]
    out += [("GreetNight", g["night"]), ("GreetMorning", g["morning"]), ("GreetAfternoon", g["afternoon"]), ("GreetEvening", g["evening"])]
    t = d["t"]
    for k in ("hour", "minute", "second", "hours", "minutes", "seconds", "world", "secondsLow", "focus", "rest", "alarm", "ringing",
              "sunrise", "sunset", "battery", "charging", "weekendLeft", "daylight"):
        out.append((f"T_{k}", t[k]))
    for var, key, nslots in (("dl", "daysLeft", 1), ("dly", "daysLeftYear", 2), ("yd", "yearDone", 1), ("oy", "ofYear", 1)):
        texts, slots = _tpl(t[key])          # the order of {n} / {year} can differ per language, so the slots are variables too
        for i in range(nslots + 1):
            out.append((f"T_{var}{i}", texts[i] if i < len(texts) else ""))
        for i in range(1, nslots + 1):
            out.append((f"T_{var}S{i}", SLOT[slots[i - 1]] if i <= len(slots) else ""))
    return out

def write_incs(skin_dir):
    langs = load()
    folder = os.path.join(skin_dir, "Languages")
    os.makedirs(folder, exist_ok=True)
    for name, d in langs.items():
        lines = [f"; {name}  -  generated by tools/gen_ini.py from tools/languages.lua. UTF-16: Rainmeter reads it natively.", "[Variables]"]
        lines += [f"{k}={v}" for k, v in variables(d)]
        with open(os.path.join(folder, f"{name}.inc"), "w", encoding="utf-16", newline="") as f:   # UTF-16 LE + BOM
            f.write("\r\n".join(lines) + "\r\n")
    return langs
